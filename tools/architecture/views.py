"""Markdown views: one page per package, and the index that links them.

Each package page holds *all* of that package's own modules, classes and
public module-level functions (its subpackages have their own pages), so a
new module, class or subpackage appears without any configuration. Classes
are drawn whether or not they take part in inheritance; a base class or
subclass in another package appears as a member-less stub. Nothing beyond
the extracted facts is drawn: no composition or usage edges are inferred.
"""
from __future__ import annotations

from .mermaid import class_diagram, package_module_flowchart
from .model import Graph
from .sources import Project


def page_name(package: str) -> str:
    return f"packages/{package}.md"


def _link_from_page(target: str) -> str:
    """Relative link from ``packages/x.md`` to a snapshot file."""
    return f"../{target}"


def _fence(text: str) -> list[str]:
    return ["```mermaid", text.rstrip("\n"), "```"]


def public_functions(project: Project, module: str) -> list[str]:
    return sorted(f.qualname for f in project.functions.values()
                  if f.module == module and f.class_id is None
                  and not f.qualname.startswith("_"))


def package_page(project: Project, package: str, members: list[str], modules: Graph,
                 classes: Graph, package_of, data_files: list[str],
                 entry_paths: dict[str, list[str]], root: str) -> tuple[str, set[str]]:
    """The page text and the set of classes it renders."""
    own = sorted(c for c in classes.nodes if classes.nodes[c]["module"] in set(members))
    related = {t for (s, t, _k) in classes.edges if s in own} | \
              {s for (s, t, _k) in classes.edges if t in own}
    stubs = frozenset(sorted(related - set(own)))
    subpackages = sorted(p for p in {package_of(m) for m in project.modules}
                         if p.rpartition(".")[0] == package)
    parent = package.rpartition(".")[0]
    out = [f"# Package `{package}`", "",
           "Generated by `tools.architecture`; do not edit. Every module, class and "
           "public module-level function of this package is listed here "
           "(subpackages have their own pages). Relations shown are extracted from "
           "the source, not inferred.", ""]
    nav = []
    if parent:
        nav.append(f"parent [`{parent}`]({parent}.md)")
    nav += [f"[`{s}`]({s}.md)" for s in subpackages]
    out += [f"Index: [all packages](../index.md)" + (" · " + " · ".join(nav) if nav else ""), ""]
    out += ["## Modules", "", "| Module | Category | Classes | Public functions |",
            "|---|---|---|---|"]
    for m in members:
        info = project.modules[m]
        cls = sorted(classes.nodes[c]["qualname"] for c in own
                     if classes.nodes[c]["module"] == m and "." not in classes.nodes[c]["qualname"])
        fns = public_functions(project, m)
        out.append(f"| `{m}` | {info.category} | "
                   + (", ".join(f"`{c}`" for c in cls) or "–") + " | "
                   + (", ".join(f"`{f}`" for f in fns) or "–") + " |")
    out.append("")
    if data_files:
        out += ["Files shipped in this directory that are **not Python and not analysed** "
                "(templates, data): " + ", ".join(f"`{f}`" for f in data_files)
                + ". Their contents (for example JavaScript in an HTML template) are "
                "invisible to every graph here.", ""]
    out += ["## Imports", "",
            "This package's modules and the import edges between them; every other "
            "package is collapsed to one dashed node (edge label: module edges merged). "
            "A dashed arrow is made only of function-scope or `TYPE_CHECKING` imports.",
            "", *_fence(package_module_flowchart(
                modules, members, package_of, root,
                f"Modules of {package} with imports in and out")), ""]
    out += ["## Classes", ""]
    if own:
        out += [f"{len(own)} class{'es' if len(own) != 1 else ''}, each with the functions "
                "defined in its body (`$`: class/static method; no parentheses: "
                "property). Edges: inheritance (`<|--`) and nesting (`*--`) only."
                + (" Stubs marked *defined elsewhere* are related classes from other "
                   "packages." if stubs else ""), "",
                *_fence(class_diagram(classes, own, root, f"Classes of {package}",
                                      stubs=stubs)), ""]
    else:
        out += ["No classes.", ""]
    touching = sorted(name for name, pkgs in entry_paths.items() if package in pkgs)
    out += ["## Entry paths through this package", ""]
    out += ([f"* [`calls/{n}.mmd`](../calls/{n}.mmd)" for n in touching]
            or ["None of the scoped call graphs reaches this package."])
    out.append("")
    return "\n".join(out), set(own)


def index_page(title: str, package_rows: list[dict], cli: dict[str, str],
               declared: list[dict], coverage: dict) -> str:
    out = [f"# Architecture index: {title}", "",
           "Generated by `tools.architecture`; do not edit. Start here. "
           "[`packages.mmd`](packages.mmd) is the package-level overview; every package "
           "below has a detail page; the entry paths are scoped static call graphs. "
           "[`coverage.json`](coverage.json) records what was discovered, what is "
           "rendered, what is deliberately excluded, and what static analysis cannot "
           "see. Narrative pages are linked from [the architecture README](../README.md).",
           "",
           "Explore class definitions in the [offline HTML atlas](class-atlas.html) or the "
           "[Mermaid containment tree](structure.mmd). "
           "The [inheritance overview](class-inheritance.mmd) shows the class hierarchy.",
           "", "## Packages", "",
           "| Package | Modules | Classes | Public functions | Not analysed (non-Python files) |",
           "|---|---|---|---|---|"]
    for row in package_rows:
        out.append(f"| [`{row['package']}`]({page_name(row['package'])}) | {row['modules']} | "
                   f"{row['classes']} | {row['public_functions']} | "
                   + (", ".join(f"`{f}`" for f in row["data_files"]) or "–") + " |")
    out += ["", "## Entry paths", "",
            "**CLI handlers**, discovered from `set_defaults(<keyword>=<function>)` "
            "(argparse subcommand dispatch, which the call graph itself cannot follow):", "",
            "| Graph | Handler |", "|---|---|"]
    out += [f"| [`calls/{n}.mmd`](calls/{n}.mmd) | `{fid}` |" for n, fid in cli.items()]
    out += ["", "**Declared Python entry paths** (from the scope file; every public entry "
            "point candidate is a root here or listed under exclusions):", "",
            "| Graph | Title | Roots | Narrative |", "|---|---|---|---|"]
    for p in declared:
        doc = f"[{p['doc']}](../../../{p['doc']})" if p["doc"] else "–"
        out.append(f"| [`calls/{p['name']}.mmd`](calls/{p['name']}.mmd) | {p['title']} | "
                   + ", ".join(f"`{r}`" for r in p["roots"]) + f" | {doc} |")
    if not declared:
        out.append("| – | none declared | – | – |")
    cov = coverage
    out += ["", "## Coverage", "",
            f"* Packages: {cov['discovered']['packages']} discovered, "
            f"{cov['rendered']['package_pages']} with a page.",
            f"* Import module records: {cov['discovered']['modules']} discovered "
            f"(including namespace placeholders), {cov['rendered']['modules']} listed on "
            "a package page.",
            f"* Classes: {cov['discovered']['classes']} discovered, "
            f"{cov['rendered']['classes']} drawn on a package page "
            f"({cov['rendered']['classes_in_inheritance_overview']} in "
            "[the inheritance overview](class-inheritance.mmd)).",
            "* Both containment views cover "
            + ", ".join(f"{cov['rendered']['containment'].get(kind, 0)} {name}"
                        for kind, name in (("package", "directories"), ("module", "Python files"),
                                           ("class", "class definitions"))) + ", leaving out files and "
            "directories that define no class.",
            f"* CLI handlers: {len(cov['discovered']['cli_handlers'])} discovered, each "
            "with a call graph.",
            f"* Public Python entry-point candidates: "
            f"{len(cov['discovered']['entry_point_candidates'])}; "
            f"{len(cov['declared']['candidates_as_roots'])} are roots of declared paths, "
            f"{len(cov['declared']['excluded'])} excluded with a reason.", "",
            "**Deliberate exclusions**", ""]
    out += [f"* `{fn}`: {reason}" for fn, reason in cov["declared"]["excluded"].items()] \
        or ["None."]
    out += ["", "**Static-analysis limits** (counts in `coverage.json`): calls through "
            "objects, `getattr`, callbacks and decorators are not edges; dynamic imports "
            "are counted, not followed; function-local classes are recorded only in the "
            "containment views; non-Python files are listed, never read. A missing edge does not "
            "mean \"never called\".", ""]
    return "\n".join(out)
