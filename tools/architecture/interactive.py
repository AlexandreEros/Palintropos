DATA_MARKER = "__ATLAS_DATA__"
ATLAS_SCHEMA = 1
PROPOSAL_SCHEMAS = (2,)
TRACE_SCHEMAS = (2,)
UNASSIGNED = "unassigned"

#: Per-edge cap on recorded call or import sites; the rest are counted.
DEFAULT_MAX_SITES = 8
#: Per-caller cap on examples of call sites that produced no edge.
MAX_UNRESOLVED_EXAMPLES = 4
#: Context lines kept around each recorded site.
SITE_CONTEXT = 2
_TEXT_CAP = 240
_ARG_CAP = 120

#: What each static edge kind claims (shown verbatim in the page legend).
EVIDENCE = {
    "call": ("static-certain", "Name bound to this definition by a def or an import/"
             "re-export chain. Certain up to run-time rebinding."),
    "instantiate": ("static-certain", "The called name resolves to this analysed class."),
    "constructor": ("structural", "Class -> the __init__ found in it or its analysed bases; "
                    "what instantiation runs unless a metaclass or __new__ intervenes. "
                    "Not a call site."),
    "self": ("receiver-lookup", "self.m()/cls.m() looked up from the enclosing class. The "
             "runtime target depends on the receiver's concrete class."),
    "super": ("receiver-lookup", "super().m(): first m after the enclosing class in its "
              "analysed bases (depth-first, not exact C3)."),
    "override": ("possible-dispatch", "A subclass redefinition of the m of a self-call: a "
                 "possible runtime target (class-hierarchy analysis), NOT an observed call."),
}


