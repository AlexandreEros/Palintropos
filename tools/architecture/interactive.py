class _Index:
    """Integer ids for every node, so edges serialize compactly."""

    def __init__(self, project: Project):
        ids = set(project.modules) | set(project.classes) | set(project.functions)
        self.ids = sorted(ids)
        self.of = {n: i for i, n in enumerate(self.ids)}


def _cut(text: str, cap: int) -> str:
    return text if len(text) <= cap else text[: cap - 1] + "\u2026"


def _type_checking_lines(tree: ast.Module) -> set[int]:
    lines: set[int] = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.If) and (dotted(node.test) or "").endswith("TYPE_CHECKING"):
            for stmt in node.body:
                lines.update(range(stmt.lineno, (stmt.end_lineno or stmt.lineno) + 1))
    return lines


def _params(fn) -> list[tuple[str, str, str | None]]:
    """``[(kind, name, annotation)]`` in call order; kind is pos/kw/*/**."""
    a = fn.node.args
    out = [("pos", p.arg, p.annotation) for p in [*a.posonlyargs, *a.args]]
    if a.vararg is not None:
        out.append(("*", a.vararg.arg, a.vararg.annotation))
    out += [("kw", p.arg, p.annotation) for p in a.kwonlyargs]
    if a.kwarg is not None:
        out.append(("**", a.kwarg.arg, a.kwarg.annotation))
    return [(k, n, ast.unparse(ann) if ann is not None else None) for k, n, ann in out]


def _defaults(fn) -> dict[str, str]:
    a = fn.node.args
    positional = [*a.posonlyargs, *a.args]
    out = {p.arg: ast.unparse(d) for p, d in zip(positional[len(positional) - len(a.defaults):],
                                                 a.defaults)}
    out.update({p.arg: ast.unparse(d) for p, d in zip(a.kwonlyargs, a.kw_defaults)
                if d is not None})
    return out


def _bind(call: ast.Call, params: list, skip_first: bool) -> list[list[str]]:
    """Arguments of ``call`` paired with the callee's parameter names, syntactically.

    ``*expr``/``**expr`` arguments cannot be bound statically; they are
    reported with the marker ``*``/``**`` and binding stops there for
    positional arguments.
    """
    positional = [n for k, n, _ in params if k == "pos"]
    if skip_first and positional:
        positional = positional[1:]
    names = {n for k, n, _ in params if k in ("pos", "kw")}
    star = next((n for k, n, _ in params if k == "*"), None)
    dstar = next((n for k, n, _ in params if k == "**"), None)
    out = []
    unpacked = False
    for i, arg in enumerate(call.args):
        text = _cut(ast.unparse(arg), _ARG_CAP)
        if isinstance(arg, ast.Starred) or unpacked:
            unpacked = True
            out.append(["*", text])
        elif i < len(positional):
            out.append([positional[i], text])
        else:
            out.append([f"*{star}" if star else "?", text])
    for kw in call.keywords:
        text = _cut(ast.unparse(kw.value), _ARG_CAP)
        if kw.arg is None:
            out.append(["**", text])
        elif kw.arg in names:
            out.append([kw.arg, text])
        else:
            out.append([f"**{dstar}" if dstar else "?" + kw.arg, text])
    return out


def _skip_receiver(kind: str, target_fn) -> bool:
    if target_fn is None or target_fn.class_id is None or target_fn.kind == "staticmethod":
        return False
    if target_fn.kind == "classmethod":
        return True
    return kind in ("self", "super", "override", "instantiate")


class _Lines:
    """The source lines a page record points at, collected sparsely."""

    def __init__(self, project: Project):
        self.text = {info.path: info_text.splitlines()
                     for info, info_text in ((i, (project.src_root / i.path).read_text("utf-8"))
                                             for i in project.files.values())}
        self.wanted: dict[str, set[int]] = defaultdict(set)

    def want(self, path: str, first: int, last: int | None = None, context: int = 0) -> None:
        lines = self.text.get(path)
        if not lines:
            return
        last = first if last is None else last
        lo, hi = max(1, first - context), min(len(lines), last + context)
        self.wanted[path].update(range(lo, hi + 1))

    def table(self) -> dict[str, dict[str, str]]:
        return {path: {str(n): self.text[path][n - 1].rstrip() for n in sorted(nums)}
                for path, nums in sorted(self.wanted.items())}


def _call_sites(project: Project, index: _Index, calls_graph, lines: _Lines, cap: int):
    """Sites behind each static call edge, plus non-edge call sites per caller."""
    edge_pos = {key: i for i, key in enumerate(sorted(calls_graph.edges))}
    sites: list[list] = [[] for _ in edge_pos]
    seen: Counter = Counter()
    unresolved: dict[int, list] = {}
    for fid in sorted(project.functions):
        fn = project.functions[fid]
        path = project.modules[fn.module].path
        local, receiver = _local_bindings(project, fn), _receiver_name(fn)
        counts: Counter = Counter()
        examples: list = []
        for stmt in fn.node.body:
            for call in ast.walk(stmt):
                if not isinstance(call, ast.Call):
                    continue
                outcome = _resolve_call(project, fn, call, local, receiver)
                text = _cut(ast.unparse(call), _TEXT_CAP)
                if isinstance(outcome, str):
                    counts[outcome] += 1
                    if outcome == "unresolved" and len(examples) < MAX_UNRESOLVED_EXAMPLES:
                        examples.append([call.lineno, outcome, _cut(ast.unparse(call.func),
                                                                    _ARG_CAP)])
                        lines.want(path, call.lineno)
                    continue
                alternatives = [index.of[t] for k, t in outcome if k == "override"]
                for kind, target in outcome:
                    pos = edge_pos[(fid, target, kind)]
                    seen[pos] += 1
                    if seen[pos] > cap:
                        continue
                    target_fn = project.functions.get(target)
                    if kind == "instantiate":
                        found = project.lookup_member(target, "__init__")
                        target_fn = (project.functions.get(found[1])
                                     if found and found[0] == "function" else None)
                    binding = (_bind(call, _params(target_fn), _skip_receiver(kind, target_fn))
                               if target_fn is not None else [])
                    site = [call.lineno, call.col_offset, text, binding]
                    if kind == "self" and alternatives:
                        site.append(alternatives)
                    sites[pos].append(site)
                    lines.want(path, call.lineno, call.end_lineno, SITE_CONTEXT)
        if counts:
            unresolved[index.of[fid]] = [dict(sorted(counts.items())), examples]
    omitted = [max(0, seen[i] - cap) for i in range(len(edge_pos))]
    return sites, omitted, unresolved, [seen[i] for i in range(len(edge_pos))]


def _import_sites(project: Project, modules_graph, lines: _Lines, cap: int):
    edges = sorted(modules_graph.edges)
    tc_cache: dict[str, set[int]] = {}
    sites: list[list] = []
    omitted: list[int] = []
    for source, target, _kind in edges:
        info = project.modules[source]
        tc = tc_cache.setdefault(source, _type_checking_lines(info.tree))
        found = []
        for stmt in ast.walk(info.tree):
            if not isinstance(stmt, (ast.Import, ast.ImportFrom)):
                continue
            if target not in info.import_candidates.get(stmt.lineno, set()):
                continue
            if isinstance(stmt, ast.Import):
                names = [a.name + (f" as {a.asname}" if a.asname else "") for a in stmt.names
                         if a.name == target or a.name.startswith(target + ".")]
            else:
                base = import_base(source, info.is_package, stmt.level, stmt.module)
                names = []
                for a in stmt.names:
                    sub = f"{base}.{a.name}"
                    as_ = f" as {a.asname}" if a.asname else ""
                    if sub == target or (base == target and sub not in project.modules):
                        names.append(a.name + as_)
            scope = ("type_checking" if stmt.lineno in tc else
                     "function" if stmt.lineno in info.function_import_lines else "module")
            found.append([stmt.lineno, scope, names, _cut(ast.unparse(stmt), _TEXT_CAP)])
        found.sort()
        for site in found[:cap]:
            lines.want(info.path, site[0], None, 1)
        sites.append(found[:cap])
        omitted.append(max(0, len(found) - cap))
    return edges, sites, omitted


def _signatures(project: Project, index: _Index, lines: _Lines) -> dict[str, list]:
    out: dict[str, list] = {}
    for fid, fn in sorted(project.functions.items()):
        node = fn.node
        defaults = _defaults(fn)
        params = [[k, n, ann, defaults.get(n)] for k, n, ann in _params(fn)]
        doc = ast.get_docstring(node) or ""
        first = (node.decorator_list[0].lineno if node.decorator_list else node.lineno)
        body = node.body[0].lineno if node.body else node.lineno
        lines.want(project.modules[fn.module].path, first, max(node.lineno, body))
        out[str(index.of[fid])] = [
            ("async " if isinstance(node, ast.AsyncFunctionDef) else "") + node.name,
            params, ast.unparse(node.returns) if node.returns is not None else None,
            _cut(doc.strip().split("\n\n")[0].replace("\n", " "), 400),
            fn.decorators, (node.end_lineno or node.lineno)]
    for cid, cls in sorted(project.classes.items()):
        node = cls.node
        doc = ast.get_docstring(node) or ""
        first = node.decorator_list[0].lineno if node.decorator_list else node.lineno
        lines.want(project.modules[cls.module].path, first, node.lineno)
        out[str(index.of[cid])] = [node.name, [], None,
                                   _cut(doc.strip().split("\n\n")[0].replace("\n", " "), 400),
                                   cls.decorators, (node.end_lineno or node.lineno),
                                   cls.base_exprs]
    return out


_COMMENT = re.compile(r"#\s?(.*)$")


def _fields(project: Project, index: _Index, lines: _Lines) -> dict[str, list]:
    """Annotated class-body assignments with the same-line comment, verbatim."""
    out: dict[str, list] = {}
    for cid, cls in sorted(project.classes.items()):
        path = project.modules[cls.module].path
        rows = []
        for stmt in cls.node.body:
            if isinstance(stmt, ast.AnnAssign) and isinstance(stmt.target, ast.Name):
                text = lines.text.get(path, [])
                line = text[stmt.end_lineno - 1] if stmt.end_lineno and text else ""
                # Only a real trailing comment token, never a '#' inside a string.
                comments = [c for c in _comments(line)] if "#" in line else []
                comment = comments[-1] if comments else None
                if comment is not None:
                    lines.want(path, stmt.lineno, stmt.end_lineno)
                rows.append([stmt.target.id, ast.unparse(stmt.annotation),
                             _cut(ast.unparse(stmt.value), _ARG_CAP) if stmt.value else None,
                             comment, stmt.lineno])
        if rows:
            out[str(index.of[cid])] = rows
    return out


def _comments(line: str):
    import io
    import tokenize
    try:
        for tok in tokenize.generate_tokens(io.StringIO(line.strip() + "\n").readline):
            if tok.type == tokenize.COMMENT:
                m = _COMMENT.match(tok.string)
                yield m.group(1).strip() if m else tok.string
    except (tokenize.TokenError, IndentationError, SyntaxError):
        return


