def build_atlas(project: Project, *, modules, calls, classes, packages_of: dict[str, str],
                entries: dict[str, dict], call_depth: int, meta: dict,
                proposal: dict | None = None, proposal_source: dict | None = None,
                traces: list[dict] | None = None, max_sites: int = DEFAULT_MAX_SITES) -> dict:
    """The page payload: a pure function of the analysed tree and the inputs."""
    index = _Index(project)
    of = index.of
    lines = _Lines(project)

    nodes = []
    for ident in index.ids:
        if ident in project.functions:
            fn = project.functions[ident]
            nodes.append([fn.kind, of[fn.module], fn.lineno, of[packages_of[fn.module]]])
        elif ident in project.classes:
            cls = project.classes[ident]
            nodes.append(["class", of[cls.module], cls.lineno, of[packages_of[cls.module]]])
        else:
            info = project.modules[ident]
            kind = info.category if info.category == "namespace" else (
                "package" if info.is_package else "module")
            nodes.append([kind, of[ident], 1, of[packages_of[ident]], info.path,
                          info.category, info.dynamic_import_calls])

    import_edges, import_sites, import_omitted = _import_sites(project, modules, lines,
                                                               max_sites)
    imports = []
    for (s, t, _k), sites in zip(import_edges, import_sites):
        scopes = modules.edges[(s, t, "imports")].get("scopes", [])
        imports.append([of[s], of[t], "+".join(sorted(scopes))])

    call_keys = sorted(calls.edges)
    call_list = [[of[s], of[t], k] for s, t, k in call_keys]
    call_index = {(of[s], of[t], k): i for i, (s, t, k) in enumerate(call_keys)}
    constructor_of: dict[int, list[int]] = defaultdict(list)
    for s, t, k in call_keys:
        if k == "constructor":
            constructor_of[of[t]].append(of[s])
    sites, omitted, unresolved, site_totals = _call_sites(project, index, calls, lines,
                                                          max_sites)
    signatures = _signatures(project, index, lines)
    fields = _fields(project, index, lines)

    groups, rule_used = assign(index.ids, proposal)
    group_names = sorted(set(groups) | set((proposal or {}).get("groups", {})) | {UNASSIGNED})
    analysis = analyse_proposal(index.ids, groups, imports, call_list, proposal)
    # A rule that assigns nothing is stale (renamed or removed code): kept visible.
    analysis["rules_matching_nothing"] = [
        r["prefix"] for i, r in enumerate((proposal or {}).get("rules", []))
        if i not in set(rule_used)]
    analysis["unassigned_modules"] = [ident for ident, g in zip(index.ids, groups)
                                      if g == UNASSIGNED and ident in project.modules]

    aligned = [align_trace(t, index, call_index, constructor_of) for t in traces or []]

    return {
        "schema": ATLAS_SCHEMA,
        "meta": {**meta, "call_depth": call_depth, "max_sites": max_sites,
                 "traversed": list(TRAVERSED_KINDS),
                 "evidence": {k: list(v) for k, v in EVIDENCE.items()}},
        "ids": index.ids,
        "nodes": nodes,
        "imports": imports,
        "import_sites": import_sites,
        "import_omitted": import_omitted,
        "calls": call_list,
        "call_sites": sites,
        "call_omitted": omitted,
        "call_site_totals": site_totals,
        "unresolved": unresolved,
        "signatures": signatures,
        "fields": fields,
        "inherits": [[of[s], of[t]] for s, t, k in sorted(classes.edges) if k == "inherits"],
        "lines": lines.table(),
        "entries": {name: {**e, "roots": [of[r] for r in e["roots"] if r in of]}
                    for name, e in sorted(entries.items())},
        "proposal": {
            "source": proposal_source,
            "status": (proposal or {}).get("status"),
            "principle": (proposal or {}).get("principle"),
            "groups": {g: ((proposal or {}).get("groups", {}).get(g)
                           or {"role": "No proposed owner: kept visible for review."})
                       for g in group_names},
            "layers": (proposal or {}).get("layers", []),
            "rules": (proposal or {}).get("rules", []),
            "exceptions": (proposal or {}).get("exceptions", []),
            "assign": [group_names.index(g) for g in groups],
            "group_names": group_names,
            "rule": rule_used,
            "analysis": analysis,
        },
        "traces": aligned,
    }


def summary(atlas: dict) -> dict:
    """The deterministic numbers ``metrics.json`` records about the page."""
    p = atlas["proposal"]
    return {
        "nodes": len(atlas["ids"]),
        "import_edges": len(atlas["imports"]),
        "call_edges": len(atlas["calls"]),
        "call_sites_recorded": sum(len(s) for s in atlas["call_sites"]),
        "call_sites_omitted_by_cap": sum(atlas["call_omitted"]),
        "import_sites_recorded": sum(len(s) for s in atlas["import_sites"]),
        "import_sites_omitted_by_cap": sum(atlas["import_omitted"]),
        "source_lines_embedded": sum(len(v) for v in atlas["lines"].values()),
        "max_sites_per_edge": atlas["meta"]["max_sites"],
        "proposal": None if not p["source"] else {
            **p["source"], "status": p["status"],
            "members": p["analysis"]["members"],
            "crossing_import_edges": p["analysis"]["imports"]["crossing_edges"],
            "crossing_call_edges": p["analysis"]["calls"]["crossing_edges"],
            "import_edges_by_direction": p["analysis"]["imports"]["by_direction"],
            "call_edges_by_direction": p["analysis"]["calls"]["by_direction"],
            "import_group_cycles": p["analysis"]["imports"]["group_cycles"],
            "import_group_cycles_without_exceptions":
                p["analysis"]["imports"]["residual_group_cycles"],
            "call_group_cycles_without_exceptions":
                p["analysis"]["calls"]["residual_group_cycles"],
            "exceptions_used": p["analysis"]["exceptions_used"],
            "rules_matching_nothing": p["analysis"]["rules_matching_nothing"],
            "unassigned_modules": p["analysis"]["unassigned_modules"],
        },
        "runtime_traces": [{"file": t["file"]["path"], "sha256": t["file"]["sha256"],
                            "scenario": t.get("scenario"),
                            "commit": (t.get("provenance") or {}).get("code", {}).get("commit"),
                            "observed_edges": len(t["edges"]), "alignment": t["alignment"]}
                           for t in atlas["traces"]],
    }


def render_html(data: dict, template: str | None = None) -> str:
    """Embed ``data`` in the template; safe against ``</script>`` in source text."""
    template = template if template is not None else TEMPLATE.read_text(encoding="utf-8")
    if template.count(DATA_MARKER) != 1:
        raise ValueError("HTML template must contain the data marker exactly once")
    # One record per line keeps diffs of the committed page reviewable.
    raw = json.dumps(data, sort_keys=True, ensure_ascii=False, indent=0,
                     separators=(",", ":"))
    safe = (raw.replace("&", "\\u0026").replace("<", "\\u003c").replace(">", "\\u003e")
            .replace("\u2028", "\\u2028").replace("\u2029", "\\u2029"))
    return template.replace(DATA_MARKER, safe)
