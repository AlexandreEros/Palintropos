def _matcher(prefixes: list[str]):
    ordered = sorted(enumerate(prefixes), key=lambda p: (-len(p[1]), p[0]))

    def match(ident: str) -> int | None:
        for i, prefix in ordered:
            if ident == prefix or ident.startswith(prefix + "."):
                return i
        return None
    return match


def assign(ids: list[str], proposal: dict | None) -> tuple[list[str], list[int]]:
    """Proposed group of every id (most specific prefix wins) and the rule used (-1: none)."""
    if not proposal:
        return [UNASSIGNED] * len(ids), [-1] * len(ids)
    rules = proposal.get("rules", [])
    match = _matcher([r["prefix"] for r in rules if not r.get("exact")])
    prefix_rules = [i for i, r in enumerate(rules) if not r.get("exact")]
    exact = {r["prefix"]: i for i, r in enumerate(rules) if r.get("exact")}
    groups, used = [], []
    for ident in ids:
        i = exact.get(ident)
        if i is None:
            j = match(ident)
            i = None if j is None else prefix_rules[j]
        groups.append(UNASSIGNED if i is None else rules[i]["group"])
        used.append(-1 if i is None else i)
    return groups, used


def _direction(proposal: dict | None):
    tiers = (proposal or {}).get("layers", [])
    rank = {g: t for t, tier in enumerate(tiers) for g in tier}

    def classify(a: str, b: str) -> str:
        if a == b:
            return "internal"
        if a not in rank or b not in rank:
            return "undeclared"
        if rank[a] < rank[b]:
            return "downward"
        if rank[a] == rank[b]:
            return "lateral"
        return "upward"
    return classify


def analyse_proposal(ids: list[str], groups: list[str], imports: list, calls: list,
                     proposal: dict | None) -> dict:
    """Cross-boundary aggregates, direction classes, exceptions and group cycles."""
    import networkx as nx

    classify = _direction(proposal)
    exceptions = (proposal or {}).get("exceptions", [])
    src_match = [_matcher([e["source"]]) for e in exceptions]
    dst_match = [_matcher([e["target"]]) for e in exceptions]

    def excepted(s: str, t: str) -> int:
        for i in range(len(exceptions)):
            if src_match[i](s) is not None and dst_match[i](t) is not None:
                return i
        return -1

    out: dict[str, Any] = {}
    exception_use = Counter()
    for name, edges, runtime_of in (
            ("imports", imports, lambda e: e[2] != "type_checking"),
            ("calls", [c for c in calls if c[2] != "constructor"], lambda e: True)):
        cells: dict[str, dict] = {}
        quotient = nx.DiGraph()          # every executed crossing edge
        residual = nx.DiGraph()          # the same without declared exceptions
        for e in edges:
            s, t = e[0], e[1]
            a, b = groups[s], groups[t]
            if a == b:
                continue
            key = f"{a}|{b}"
            cell = cells.setdefault(key, {"edges": 0, "runtime_edges": 0,
                                          "direction": classify(a, b), "excepted": 0})
            cell["edges"] += 1
            if runtime_of(e):
                cell["runtime_edges"] += 1
                quotient.add_edge(a, b)
            x = excepted(ids[s], ids[t])
            if x >= 0:
                cell["excepted"] += 1
                exception_use[x] += 1
            elif runtime_of(e):
                residual.add_edge(a, b)

        def cycles(graph):
            return sorted(sorted(c) for c in nx.strongly_connected_components(graph)
                          if len(c) > 1)
        sccs = cycles(quotient)
        directions = Counter()
        for cell in cells.values():
            directions[cell["direction"]] += cell["edges"] - cell["excepted"]
        out[name] = {"cells": dict(sorted(cells.items())), "group_cycles": sccs,
                     "residual_group_cycles": cycles(residual),
                     "crossing_edges": sum(c["edges"] for c in cells.values()),
                     "by_direction": dict(sorted(directions.items()))}
    out["exceptions_used"] = [exception_use[i] for i in range(len(exceptions))]
    members = Counter(groups)
    out["members"] = dict(sorted(members.items()))
    return out


