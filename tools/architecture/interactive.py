"""Offline interactive architecture atlas: ``interactive.html`` of a snapshot.

Generated by :func:`tools.architecture.generate.render` with every other
output; this module adds no new extraction rule. It joins what the generator
already computed (import graph, static call graph, class graph, discovered
entry paths) with source-level detail recovered from the same in-memory AST:

* every import statement behind an import edge: imported symbols, aliases,
  line, and scope (``module``, ``function`` or ``type_checking``);
* every call site behind a static call edge (capped per edge, the omission
  counted): the expression, its arguments bound to the callee's parameters,
  and the callee's parameter/return annotations as written;
* per caller, the call sites that are *not* edges (``external``, ``builtin``,
  ``unresolved``) with a few examples, so the gaps stay visible;
* annotated class-level fields with the comment on their line, verbatim (an
  explicit source contract such as ``radius: float  # m``; nothing is
  inferred from names);
* a sparse table of the source lines those records point at.

Two optional *inputs* are joined as well, and both are files under version
control whose SHA-256 is recorded:

* a proposed-package overlay (``docs/architecture/proposed-packages.json``):
  editable responsibility groups assigned by id prefix, an intended dependency
  order and declared exceptions. It is a hypothesis being evaluated; it never
  changes any measurement of the current code;
* runtime evidence (``docs/architecture/evidence/runtime/*.json``) written by
  :mod:`tools.architecture.runtime_capture`, possibly at another revision. Each
  observation keeps its own revision and is aligned with the static graph
  only by name; the alignment category says how (or that it could not be).

Nothing here imports the analysed package. The page is one self-contained
HTML file with the data embedded as JSON (no network, no CDN, no library).
"""
