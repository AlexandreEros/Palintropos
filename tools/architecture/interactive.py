def _static_id(name: str, index: _Index) -> tuple[str, str]:
    """Runtime ``module.co_qualname`` -> (static id, how it was mapped)."""
    if name in index.of:
        return name, "exact"
    if ".__create_fn__.<locals>." in name:
        # Code generated at run time (dataclasses): no source definition.
        return name, "generated"
    if ".<locals>." in name:
        outer = name.split(".<locals>.", 1)[0]
        if outer in index.of:
            return outer, "enclosing-function"
    if name.endswith(".<module>"):
        mod = name[: -len(".<module>")]
        if mod in index.of:
            return mod, "module-scope"
    head = name.split(".<", 1)[0]
    if head in index.of and head != name:
        return head, "enclosing-scope"
    return name, "not-in-static-index"


def align_trace(trace: dict, index: _Index, call_index: dict, constructor_of: dict) -> dict:
    """Compact, aligned copy of a trace for the page (provenance kept verbatim)."""
    edges = []
    categories: Counter = Counter()
    for e in trace.get("edges", []):
        s_id, s_map = _static_id(e["source"], index)
        t_id, t_map = _static_id(e["target"], index)
        si, ti = index.of.get(s_id), index.of.get(t_id)
        match: list = []
        if si is not None and ti is not None:
            match = [[k, call_index[(si, ti, k)]] for k in TRAVERSED_KINDS
                     if (si, ti, k) in call_index]
            if not match and t_id.endswith(".__init__"):
                for cls in constructor_of.get(ti, []):
                    if (si, cls, "instantiate") in call_index:
                        match.append(["instantiate+constructor",
                                      call_index[(si, cls, "instantiate")]])
        if "generated" in (s_map, t_map):
            category = "generated-code"
        elif s_map == "not-in-static-index" or t_map == "not-in-static-index":
            category = "unmapped"
        elif s_id == t_id:
            category = "same-static-node"
        elif match:
            category = "corroborated"
        else:
            category = "runtime-only"
        categories[category] += 1
        edges.append({"s": si if si is not None else e["source"],
                      "t": ti if ti is not None else e["target"],
                      "rs": e["source"], "rt": e["target"], "map": [s_map, t_map],
                      "category": category, "static": match,
                      **{k: e[k] for k in ("count", "phases", "wall_ns_inclusive", "lines")
                         if k in e}})
    keep = {k: trace[k] for k in ("id", "scenario", "description", "provenance", "semantics",
                                  "summary", "boundaries", "device_events", "functions",
                                  "verification", "attachments", "error") if k in trace}
    return {**keep, "file": trace["_file"], "edges": edges,
            "alignment": dict(sorted(categories.items()))}


