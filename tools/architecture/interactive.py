def _sha256_text(path: Path) -> str:
    # LF-normalized, like provenance.working_tree: identity is the committed text.
    return hashlib.sha256(path.read_bytes().replace(b"\r\n", b"\n")).hexdigest()


class AtlasInputError(ValueError):
    """A proposal or trace file is malformed."""


def load_proposal(root: Path, rel: str | None) -> tuple[dict | None, dict | None]:
    """``(proposal, {"path", "sha256"})`` or ``(None, None)`` when not given."""
    if rel is None:
        return None, None
    path = root / rel
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        raise AtlasInputError(f"{rel}: cannot read proposal: {exc}") from None
    if data.get("schema") not in PROPOSAL_SCHEMAS:
        raise AtlasInputError(f"{rel}: proposal schema {data.get('schema')!r} not in "
                              f"{PROPOSAL_SCHEMAS}")
    groups = data.get("groups")
    if not isinstance(groups, dict) or not groups:
        raise AtlasInputError(f"{rel}: 'groups' must be a non-empty object")
    for i, rule in enumerate(data.get("rules", [])):
        if not isinstance(rule, dict) or not rule.get("prefix") or rule.get("group") not in groups:
            raise AtlasInputError(f"{rel}: rule {i} needs a prefix and a declared group: {rule!r}")
    tiers = data.get("layers", [])
    listed = [g for tier in tiers for g in tier]
    unknown = sorted(set(listed) - set(groups))
    if unknown or len(listed) != len(set(listed)):
        raise AtlasInputError(f"{rel}: 'layers' must list declared groups once each "
                              f"(unknown: {unknown})")
    for i, exc in enumerate(data.get("exceptions", [])):
        if not all(exc.get(k) for k in ("source", "target", "reason")):
            raise AtlasInputError(f"{rel}: exception {i} needs source, target and reason")
    return data, {"path": rel, "sha256": _sha256_text(path)}


def load_traces(root: Path, rel: str | None) -> list[dict]:
    """Every ``*.json`` runtime trace under ``rel`` (sorted), with its file identity."""
    if rel is None or not (root / rel).is_dir():
        return []
    traces = []
    for path in sorted((root / rel).glob("*.json")):
        name = f"{rel}/{path.name}"
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
        except ValueError as exc:
            raise AtlasInputError(f"{name}: not JSON: {exc}") from None
        if data.get("schema") not in TRACE_SCHEMAS:
            raise AtlasInputError(f"{name}: trace schema {data.get('schema')!r} not in "
                                  f"{TRACE_SCHEMAS} (re-capture with runtime_capture)")
        data["_file"] = {"path": name, "sha256": _sha256_text(path)}
        traces.append(data)
    return traces


