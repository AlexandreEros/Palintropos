"""Mermaid renderers for the neutral graph model.

Identifiers are an injective, deterministic encoding of the node name
(:func:`node_id`), so adding or removing an unrelated node never renames the
others and Mermaid keywords such as ``end`` cannot collide with a node id.
Human-readable text goes into quoted labels, escaped by :func:`label`.
"""
from __future__ import annotations

from collections import defaultdict

from . import TOOL_VERSION
from .model import Graph

HEADER = f"%% Generated by tools.architecture {TOOL_VERSION}. Do not edit by hand."


def node_id(name: str, prefix: str = "n") -> str:
    """Injective map from an arbitrary string to a Mermaid-safe identifier.

    Letters and digits pass through; ``_`` becomes ``__``; ``.`` becomes
    ``_o``; any other character becomes ``_x<hex>_``.
    """
    out = [prefix, "_"]
    for ch in name:
        if ch.isascii() and ch.isalnum():
            out.append(ch)
        elif ch == "_":
            out.append("__")
        elif ch == ".":
            out.append("_o")
        else:
            out.append(f"_x{ord(ch):x}_")
    return "".join(out)


_ESCAPES = {'"': "#quot;", "<": "#lt;", ">": "#gt;", "#": "#35;", "|": "#124;",
            "[": "#91;", "]": "#93;", "{": "#123;", "}": "#125;", "\n": " "}


def _label_text(text: str) -> str:
    # Quoted labels are markdown too: ``__init__`` would render as bold "init".
    return "".join("#95;" if ch == "_" else _ESCAPES.get(ch, ch) for ch in text)


def label(text: str) -> str:
    """Quoted Mermaid label text with Mermaid-significant characters escaped."""
    return '"' + _label_text(text) + '"'


def member_text(text: str) -> str:
    """Unquoted classDiagram member text: Mermaid reads ``_x_`` as emphasis
    (``__init__`` would render as bold "init"), so ``_`` is written as an
    entity along with the other Mermaid-significant characters."""
    return "".join("#95;" if ch == "_" else _ESCAPES.get(ch, ch) for ch in text)


def _lines(*parts: str) -> str:
    return "\n".join(parts) + "\n"


def _short(name: str, root: str) -> str:
    """Drop the common root prefix from a dotted name for display."""
    return name[len(root) + 1:] if name.startswith(root + ".") else name


# -- module / package graphs ----------------------------------------------
#: Styling of an edge that contradicts the declared layer order.
UPWARD_STYLE = "stroke:#d62728,stroke-width:2px"
#: Styling of the legend node of a layered drawing (not a package).
LEGEND_STYLE = "fill:none,stroke:#999,stroke-dasharray:2 2"
#: Text wrapping width (px) for a layered drawing. Mermaid's default, 200,
#: breaks legend lines mid-phrase; it changes text layout only, not the graph.
LAYERED_WRAPPING = '%%{init: {"flowchart": {"wrappingWidth": 700}}}%%'


def label_lines(lines: list[str]) -> str:
    """Quoted label of several lines: each escaped, joined by ``<br>``."""
    return '"' + "<br>".join(_label_text(line) for line in lines) + '"'


def _package_node(agg: Graph, pkg: str, root: str) -> str:
    count = agg.nodes[pkg]["modules"]
    name = pkg if pkg == root else _short(pkg, root)
    text = f"{name} ({count} module{'' if count == 1 else 's'})"
    return f"{node_id(pkg)}[{label(text)}]"


def package_flowchart(agg: Graph, root: str, title: str,
                      boxes: list[tuple[str, str, list[str]]] | None = None,
                      upward: set[tuple[str, str]] = frozenset(),
                      legend: list[str] | None = None) -> str:
    """Package-level import graph; every edge of ``agg`` is drawn.

    Edge label = number of module-level import edges merged into the edge.
    An edge made only of ``TYPE_CHECKING`` imports (``runtime_module_edges``
    is 0) is dashed and labelled ``type-only``.

    Without ``boxes`` this is a plain dependency graph. With ``boxes``,
    ``(name, caption, packages)`` in declaration order, the packages are
    drawn inside one box per layer, top to bottom; the ``(source, target)``
    pairs in ``upward`` are labelled ``up`` and styled with
    :data:`UPWARD_STYLE`; and ``legend`` lines, if any, become a standalone
    node stating where the declaration came from. Edges always connect the
    two packages themselves, never a box, so nothing is merged or rerouted.
    """
    out = [HEADER, f"%% {title}"]
    out += [LAYERED_WRAPPING, "flowchart TD"] if boxes else ["flowchart LR"]
    if boxes:
        if legend:
            out.append(f"    legend[{label_lines(legend)}]")
        for name, caption, packages in boxes:
            out.append(f"    subgraph {node_id(name, 'g')}[{label(caption)}]")
            out.extend(f"        {_package_node(agg, pkg, root)}" for pkg in packages)
            out.append("    end")
    else:
        out.extend(f"    {_package_node(agg, pkg, root)}" for pkg in sorted(agg.nodes))
    styled = []
    for index, (s, t, k) in enumerate(sorted(agg.edges)):
        attrs = agg.edges[(s, t, k)]
        type_only = attrs.get("runtime_module_edges") == 0
        text = str(attrs["module_edges"])
        if (s, t) in upward:
            styled.append(index)
            text += " up"
        if type_only:
            text += ", type-only"
        arrow = "-.->" if type_only else "-->"
        shown = text if text.isdigit() else label(text)
        out.append(f"    {node_id(s)} {arrow}|{shown}| {node_id(t)}")
    if styled:
        out.append(f"    linkStyle {','.join(str(i) for i in styled)} {UPWARD_STYLE}")
    if boxes and legend:
        out.append(f"    style legend {LEGEND_STYLE}")
    return _lines(*out)


def module_flowchart(graph: Graph, nodes: list[str], root: str, title: str,
                     group_by) -> str:
    """Module-level flowchart restricted to ``nodes``, grouped into subgraphs.

    ``group_by(module) -> group name``. Edges carrying only ``function`` or
    ``type_checking`` statements are drawn dashed and labelled with their scope.
    """
    keep = set(nodes)
    groups: dict[str, list[str]] = defaultdict(list)
    for n in sorted(keep):
        groups[group_by(n)].append(n)
    out = [HEADER, f"%% {title}", "flowchart LR"]
    for group in sorted(groups):
        out.append(f"    subgraph {node_id(group, 'g')}[{label(_short(group, root) if group != root else root)}]")
        for n in groups[group]:
            out.append(f"        {node_id(n)}[{label(_short(n, root))}]")
        out.append("    end")
    for (s, t, k) in sorted(graph.edges):
        if s in keep and t in keep:
            scopes = graph.edges[(s, t, k)]["scopes"]
            if "module" in scopes:
                out.append(f"    {node_id(s)} --> {node_id(t)}")
            else:
                out.append(f"    {node_id(s)} -.->|{'+'.join(scopes)}| {node_id(t)}")
    return _lines(*out)


def package_module_flowchart(graph: Graph, members: list[str], package_of, root: str,
                             title: str) -> str:
    """The modules of one package and their import edges, with every other
    package collapsed to one node: imports out of the package point at the
    target's package, imports into it come from the importer's package.

    Edge label on a collapsed edge = number of module edges merged. Dashed:
    every merged import is function-scope or ``TYPE_CHECKING`` (none runs
    when the importing module is imported).
    """
    keep = set(members)
    out = [HEADER, f"%% {title}", "flowchart LR"]
    pkg = package_of(members[0])
    out.append(f"    subgraph {node_id(pkg, 'g')}[{label(_short(pkg, root) if pkg != root else root)}]")
    for m in sorted(keep):
        out.append(f"        {node_id(m)}[{label(_short(m, root))}]")
    out.append("    end")
    merged: dict[tuple[str, str], list[int]] = {}
    inner = []
    for (s, t, _k) in sorted(graph.edges):
        runtime = "module" in graph.edges[(s, t, _k)]["scopes"]
        if s in keep and t in keep:
            inner.append((s, t, runtime))
        elif s in keep:
            merged.setdefault((s, "p:" + package_of(t)), [0, 0])
            merged[(s, "p:" + package_of(t))][0] += 1
            merged[(s, "p:" + package_of(t))][1] += runtime
        elif t in keep:
            merged.setdefault(("p:" + package_of(s), t), [0, 0])
            merged[("p:" + package_of(s), t)][0] += 1
            merged[("p:" + package_of(s), t)][1] += runtime
    others = sorted({n[2:] for pair in merged for n in pair if n.startswith("p:")})
    for other in others:
        out.append(f"    {node_id(other, 'p')}[{label('package ' + _short(other, root))}]")

    def ref(n: str) -> str:
        return node_id(n[2:], "p") if n.startswith("p:") else node_id(n)
    for s, t, runtime in inner:
        out.append(f"    {node_id(s)} {'-->' if runtime else '-.->'} {node_id(t)}")
    for (s, t), (count, runtime) in sorted(merged.items()):
        arrow = "-->" if runtime else "-.->"
        out.append(f"    {ref(s)} {arrow}|{count}| {ref(t)}")
    out.append("    classDef other fill:none,stroke-dasharray:3 3")
    for other in others:
        out.append(f"    class {node_id(other, 'p')} other")
    return _lines(*out)


# -- class graph -----------------------------------------------------------
_MEMBER_MARK = {"classmethod": "$", "staticmethod": "$"}


def class_diagram(graph: Graph, classes: list[str], root: str, title: str,
                  with_members: bool = True, stubs: frozenset[str] = frozenset()) -> str:
    """Mermaid ``classDiagram`` of the given classes and edges among them.

    Classes in ``stubs`` are drawn by name only (no members), marked as
    defined elsewhere: a base or nested class outside the drawn scope.
    """
    keep = set(classes) | set(stubs)
    out = [HEADER, f"%% {title}", "classDiagram", "    direction LR"]
    for cid in sorted(keep):
        attrs = graph.nodes[cid]
        text = f"{attrs['qualname']} ({_short(attrs['module'], root)})"
        if cid in stubs:
            out.append(f"    class {node_id(cid, 'c')}[{label(text + ', defined elsewhere')}]")
            continue
        out.append(f"    class {node_id(cid, 'c')}[{label(text)}]")
        if with_members:
            for member in attrs["members"]:
                suffix = _MEMBER_MARK.get(member["kind"], "")
                shown = f"{member['name']}()" if member["kind"] != "property" else member["name"]
                out.append(f"    {node_id(cid, 'c')} : +{member_text(shown)}{suffix}")
        for base in attrs["external_bases"]:
            out.append(f"    {node_id(cid, 'c')} : external base {member_text(base)}")
    for (s, t, k) in sorted(graph.edges):
        if s in keep and t in keep:
            arrow = "<|--" if k == "inherits" else "*--"
            # Mermaid draws "Parent <|-- Child"; our edges run child -> parent.
            out.append(f"    {node_id(t, 'c')} {arrow} {node_id(s, 'c')}")
    return _lines(*out)


# -- call graphs -----------------------------------------------------------
_ARROWS = {
    "call": "-->",
    "instantiate": "-->|instantiate|",
    "constructor": "-->|#95;#95;init#95;#95;|",  # "__init__", not bold "init"
    "super": "-->|super|",
    "self": "-.->|self|",
    "override": "-.->|override?|",
}


def call_flowchart(sub: Graph, root: str, title: str, roots: list[str]) -> str:
    """Scoped call graph grouped by module; dispatch-dependent edges dashed."""
    out = [HEADER, f"%% {title}", "flowchart LR"]
    by_module: dict[str, list[str]] = defaultdict(list)
    for n in sorted(sub.nodes):
        by_module[sub.nodes[n]["module"]].append(n)
    for module in sorted(by_module):
        out.append(f"    subgraph {node_id(module, 'g')}[{label(_short(module, root))}]")
        for n in by_module[module]:
            attrs = sub.nodes[n]
            if attrs["type"] == "class":
                out.append(f"        {node_id(n)}{{{{{label(attrs['qualname'])}}}}}")
            else:
                out.append(f"        {node_id(n)}[{label(attrs['qualname'] + '()')}]")
        out.append("    end")
    for (s, t, k) in sorted(sub.edges):
        out.append(f"    {node_id(s)} {_ARROWS[k]} {node_id(t)}")
    out.append("    classDef root stroke-width:3px")
    out.append("    classDef truncated stroke-dasharray:4 3")
    for r in sorted(roots):
        out.append(f"    class {node_id(r)} root")
    for n in sorted(sub.nodes):
        if sub.nodes[n].get("truncated"):
            out.append(f"    class {node_id(n)} truncated")
    return _lines(*out)
